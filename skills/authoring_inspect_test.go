package skills

import (
	"io/fs"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"
)

func TestInspectAuthoringNamesEachProblem(t *testing.T) {
	t.Parallel()
	header := AuthoringProblem{"write-prd header is not the declared one", true}
	link := AuthoringProblem{".claude/skills/write-prd does not lead to .agents/skills/write-prd, so Claude Code does not load the declared header; link it there", false}
	missing := AuthoringProblem{".claude/agents/roundfix-researcher.md is missing", true}
	differs := AuthoringProblem{".claude/agents/roundfix-prd-author.md differs from the declaration", true}
	conflict := func(name string) AuthoringProblem {
		return AuthoringProblem{".claude/agents/" + name + ".md exists and was not generated by Roundfix; installation will not overwrite it, so move or rename it", false}
	}
	for _, name := range []string{"clean", "header", "link", "missing", "differs", "conflict", "no_declared_entry", "order", "nothing_declared", "missing_skill", "quoted_header", "effort_header", "extra_header", "leftovers_without_declaration"} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			declaration := authoringFixtureDeclaration()
			if name == "nothing_declared" {
				declaration = nil
			}
			if _, err := Install(t.Context(), InstallRequest{ProjectDir: root, Authoring: declaration}); err != nil {
				t.Fatal(err)
			}
			if name != "link" && name != "order" && name != "nothing_declared" {
				linkAuthoringInspectorFixture(t, root)
			}
			var want []AuthoringProblem
			switch name {
			case "header", "effort_header", "extra_header", "quoted_header":
				path := filepath.Join(root, ".agents", "skills", "write-prd", "SKILL.md")
				data, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				text := string(data)
				switch name {
				case "header":
					text = strings.Replace(text, "model: opus", "model: sonnet", 1)
				case "effort_header":
					text = strings.Replace(text, "effort: xhigh", "effort: high", 1)
				case "extra_header":
					declaration.Entries["prd"] = AuthoringEntry{Model: "opus"}
				case "quoted_header":
					text = strings.Replace(text, "model: opus", `model: "opus"`, 1)
					text = strings.Replace(text, "effort: xhigh", `effort: 'xhigh'`, 1)
				}
				writeAuthoringFixture(t, root, ".agents/skills/write-prd/SKILL.md", text)
				if name != "quoted_header" {
					want = []AuthoringProblem{header}
				}
				if name == "extra_header" {
					want = append(want, differs)
				}
			case "link":
				want = []AuthoringProblem{link}
			case "missing":
				if err := os.Remove(filepath.Join(root, ".claude", "agents", "roundfix-researcher.md")); err != nil {
					t.Fatal(err)
				}
				want = []AuthoringProblem{missing}
			case "differs":
				path := filepath.Join(root, ".claude", "agents", "roundfix-prd-author.md")
				data, err := os.ReadFile(path)
				if err != nil {
					t.Fatal(err)
				}
				writeAuthoringFixture(t, root, ".claude/agents/roundfix-prd-author.md", string(data)+"changed\n")
				want = []AuthoringProblem{differs}
			case "conflict":
				writeAuthoringFixture(t, root, ".claude/agents/roundfix-prd-author.md", "hand-written author\n")
				writeAuthoringFixture(t, root, ".claude/agents/roundfix-idea-author.md", "hand-written idea\n")
				want = []AuthoringProblem{conflict("roundfix-prd-author"), conflict("roundfix-idea-author")}
			case "no_declared_entry":
				delete(declaration.Entries, "research")
				want = []AuthoringProblem{{".claude/agents/roundfix-researcher.md has no declared entry", true}}
			case "order":
				declaration.Entries["prd"] = AuthoringEntry{Model: "sonnet", Effort: "xhigh"}
				if err := os.Remove(filepath.Join(root, ".claude", "agents", "roundfix-researcher.md")); err != nil {
					t.Fatal(err)
				}
				want = []AuthoringProblem{header, link, differs, missing}
			case "leftovers_without_declaration":
				declaration = nil
				want = []AuthoringProblem{
					{".claude/agents/roundfix-prd-author.md has no declared entry", true},
					{".claude/agents/roundfix-researcher.md has no declared entry", true},
				}
			case "nothing_declared":
				writeAuthoringFixture(t, root, ".claude/agents/roundfix-prd-author.md", "hand-written\n")
			case "missing_skill":
				if err := os.Remove(filepath.Join(root, ".agents", "skills", "write-prd", "SKILL.md")); err != nil {
					t.Fatal(err)
				}
			}
			before := inspectAuthoringTreeSnapshot(t, root)
			got := InspectAuthoring(root, declaration)
			if got.Harness != "claude" || !reflect.DeepEqual(got.Problems, want) {
				t.Fatalf("state=%+v want problems=%+v", got, want)
			}
			var declared []string
			if declaration != nil {
				declared = []string{"prd"}
				if _, ok := declaration.Entries["research"]; ok {
					declared = append(declared, "research")
				}
			}
			if !reflect.DeepEqual(got.Declared, declared) {
				t.Fatalf("declared=%v want=%v", got.Declared, declared)
			}
			if after := inspectAuthoringTreeSnapshot(t, root); !reflect.DeepEqual(before, after) {
				t.Fatal("inspector changed files, directories or links")
			}
			if name == "conflict" {
				_, err := Install(t.Context(), InstallRequest{ProjectDir: root, Authoring: declaration})
				wantErr := ".claude/agents/roundfix-idea-author.md exists and was not generated by Roundfix; move or rename it, then run roundfix skills install --target project again"
				if err == nil || err.Error() != wantErr {
					t.Fatalf("install error=%v want=%s", err, wantErr)
				}
				if after := inspectAuthoringTreeSnapshot(t, root); !reflect.DeepEqual(before, after) {
					t.Fatal("refused installation changed the tree")
				}
			}
		})
	}
	for _, kind := range []string{"copy", "dangling", "whole_directory"} {
		t.Run("link/"+kind, func(t *testing.T) {
			root := t.TempDir()
			declaration := authoringFixtureDeclaration()
			if _, err := Install(t.Context(), InstallRequest{ProjectDir: root, Authoring: declaration}); err != nil {
				t.Fatal(err)
			}
			switch kind {
			case "copy":
				writeAuthoringFixture(t, root, ".claude/skills/write-prd/SKILL.md", "copy\n")
			case "dangling":
				if err := os.MkdirAll(filepath.Join(root, ".claude", "skills"), 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(filepath.Join(root, "absent"), filepath.Join(root, ".claude", "skills", "write-prd")); err != nil {
					t.Fatal(err)
				}
			case "whole_directory":
				if err := os.Symlink(filepath.Join(root, ".agents", "skills"), filepath.Join(root, ".claude", "skills")); err != nil {
					t.Fatal(err)
				}
			}
			before := inspectAuthoringTreeSnapshot(t, root)
			want := []AuthoringProblem{link}
			if kind == "whole_directory" {
				want = nil
			}
			if got := InspectAuthoring(root, declaration); !reflect.DeepEqual(got.Problems, want) {
				t.Fatalf("problems=%+v want=%+v", got.Problems, want)
			}
			if !reflect.DeepEqual(before, inspectAuthoringTreeSnapshot(t, root)) {
				t.Fatal("inspection changed tree or links")
			}
		})
	}
}

func linkAuthoringInspectorFixture(t *testing.T, root string) {
	t.Helper()
	path := filepath.Join(root, ".claude", "skills", "write-prd")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(filepath.Join(root, ".agents", "skills", "write-prd"), path); err != nil {
		t.Fatal(err)
	}
}

// WalkDir does not follow symbolic links, including a dangling link. Include
// directory metadata so even a create-and-remove write would be observable.
func inspectAuthoringTreeSnapshot(t *testing.T, root string) map[string]authoringFileSnapshot {
	t.Helper()
	result := map[string]authoringFileSnapshot{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		var data string
		if info.Mode()&os.ModeSymlink != 0 {
			data, err = os.Readlink(path)
		} else if info.Mode().IsRegular() {
			var content []byte
			content, err = os.ReadFile(path)
			data = string(content)
		}
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		result[filepath.ToSlash(relative)] = authoringFileSnapshot{data, info.Mode(), info.ModTime().String()}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return result
}
