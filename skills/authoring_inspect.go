package skills

import (
	"bytes"
	"errors"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

// AuthoringState describes the declaration and the installed files it governs.
type AuthoringState struct {
	Harness  string
	Declared []string
	Problems []AuthoringProblem
}

// AuthoringProblem names a mismatch and whether installation can repair it.
type AuthoringProblem struct {
	Text        string
	Installable bool
}

// InspectAuthoring only reads installed headers, directory identities and the
// five generated names. It never repairs a header, file or Claude Skill Link.
func InspectAuthoring(root string, declaration *AuthoringDeclaration) AuthoringState {
	state := AuthoringState{Harness: "claude"}
	var entries map[string]AuthoringEntry
	if declaration != nil {
		state.Harness = declaration.Harness
		entries = declaration.Entries
	}
	for _, key := range authoringKeys() {
		if _, ok := entries[key]; ok {
			state.Declared = append(state.Declared, key)
		}
	}
	for _, phase := range AuthoringPhases() {
		entry, ok := entries[phase.Key]
		if !ok {
			continue
		}
		skillPath := filepath.Join(root, ".agents", "skills", phase.Skill)
		data, err := os.ReadFile(filepath.Join(skillPath, "SKILL.md"))
		if !errors.Is(err, os.ErrNotExist) && (err != nil || !declaredHeaderMatches(data, entry)) {
			state.Problems = append(state.Problems, AuthoringProblem{phase.Skill + " header is not the declared one", true})
		}
		claude, claudeErr := os.Stat(filepath.Join(root, ".claude", "skills", phase.Skill))
		installed, installedErr := os.Stat(skillPath)
		if claudeErr != nil || installedErr != nil || !claude.IsDir() || !installed.IsDir() || !os.SameFile(claude, installed) {
			state.Problems = append(state.Problems, AuthoringProblem{".claude/skills/" + phase.Skill + " does not lead to .agents/skills/" + phase.Skill + ", so Claude Code does not load the declared header; link it there", false})
		}
	}
	repository, err := os.OpenRoot(root)
	if err != nil {
		if len(state.Declared) > 0 {
			state.Problems = append(state.Problems, AuthoringProblem{"open repository root " + root + ": " + err.Error(), false})
		}
		return state
	}
	defer func() { _ = repository.Close() }()
	// An unreachable .claude/agents is installation's refusal too, so it is
	// named once and never as a handwritten-file conflict. Without a
	// declaration nothing there is Roundfix's to report.
	if err := checkAuthoringAgentsDirectory(repository); err != nil {
		if len(state.Declared) > 0 {
			state.Problems = append(state.Problems, AuthoringProblem{err.Error(), false})
		}
		return state
	}
	// Declared generated files precede leftover names, independently of the
	// phase whose header or link was reported above. A read failure is named
	// as itself, never as a conflict, and installation does not repair it.
	for _, key := range state.Declared {
		path, exists, owned, err := generatedAuthoringFile(repository, key)
		switch {
		case err != nil:
			state.Problems = append(state.Problems, AuthoringProblem{err.Error(), false})
		case !exists:
			state.Problems = append(state.Problems, AuthoringProblem{path + " is missing", true})
		case !owned:
			state.Problems = append(state.Problems, authoringConflict(path))
		default:
			_, expected, generateErr := GeneratedSubagent(state.Harness, key, entries[key])
			actual, readErr := repository.ReadFile(path)
			if generateErr != nil || readErr != nil || !bytes.Equal(actual, expected) {
				state.Problems = append(state.Problems, AuthoringProblem{path + " differs from the declaration", true})
			}
		}
	}
	for _, key := range authoringKeys() {
		if _, ok := entries[key]; ok {
			continue
		}
		path, exists, owned, err := generatedAuthoringFile(repository, key)
		switch {
		case owned:
			state.Problems = append(state.Problems, AuthoringProblem{path + " has no declared entry", true})
		case len(state.Declared) == 0:
		case err != nil:
			state.Problems = append(state.Problems, AuthoringProblem{err.Error(), false})
		case exists:
			state.Problems = append(state.Problems, authoringConflict(path))
		}
	}
	return state
}

func authoringConflict(path string) AuthoringProblem {
	return AuthoringProblem{path + " exists and was not generated by Roundfix; installation will not overwrite it, so move or rename it", false}
}

func declaredHeaderMatches(data []byte, entry AuthoringEntry) bool {
	start, end, err := frontmatterEnd(data)
	if err != nil {
		return false
	}
	var header struct {
		Model  string `yaml:"model"`
		Effort string `yaml:"effort"`
	}
	if err := yaml.Unmarshal(data[start:end], &header); err != nil {
		return false
	}
	return header.Model == entry.Model && header.Effort == entry.Effort
}
