func TestMeasuredSanctionedOwnershipMatchesRecords(t *testing.T) {
	// Sequential: child commands rewrite one isolated repository fixture.
	repository := newDerivedRegenerationFixture(t)
	baselineRoot := filepath.Join(repository, "internal", "baseline")
	fileSystem := os.DirFS(baselineRoot)
	roots := derivedDigestScanRoots(t)
	records, err := readDerivedOwnershipRecords(fileSystem, roots)
	if err != nil {
		t.Fatal(err)
	}
	resolved, err := validateDerivedOwnership(fileSystem, roots)
	if err != nil {
		t.Fatal(err)
	}
	cacheRoot := filepath.Join(repository, ".gocache")
	clean := snapshotDerivedTreeAt(t, baselineRoot, roots)
	sanctionedProbes := declaredSanctionedProbes(t, records)
	if err := exerciseDeclaredRegenerationStep(
		t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
		"make baseline-digests", sanctionedProbes, nil,
	); err != nil {
		t.Fatal(err)
	}

	measured := make(map[string]struct{})
	for _, probe := range sanctionedProbes {
		recordPath := derivedRecordPathForArtifact(t, fileSystem, roots, resolved, probe.path)
		measured[recordPath] = struct{}{}
	}

	skillPath := filepath.Join(repository, ".agents", "skills", "qa-gate", "SKILL.md")
	skill, err := os.ReadFile(skillPath)
	if err != nil {
		t.Fatalf("read owned Skill fixture: %v", err)
	}
	skill = append(skill, []byte("\n<!-- derived ownership measurement fixture -->\n")...)
	if err := os.WriteFile(skillPath, skill, 0o644); err != nil {
		t.Fatalf("edit owned Skill fixture: %v", err)
	}

	if err := runDeclaredRegenerationStep(t.Context(), repository, cacheRoot, "make skills-sync"); err != nil {
		t.Fatal(err)
	}
	before := snapshotDerivedTreeAt(t, baselineRoot, roots)
	if err := runDeclaredRegenerationStep(t.Context(), repository, cacheRoot, "make baseline-digests"); err != nil {
		t.Fatal(err)
	}
	after := snapshotDerivedTreeAt(t, baselineRoot, roots)

	for artifactPath, afterArtifact := range after {
		beforeArtifact, existed := before[artifactPath]
		if existed && reflect.DeepEqual(afterArtifact, beforeArtifact) {
			continue
		}
		recordPath := derivedRecordPathForArtifact(t, fileSystem, roots, resolved, artifactPath)
		measured[recordPath] = struct{}{}
	}
	for artifactPath := range before {
		if _, exists := after[artifactPath]; exists {
			continue
		}
		recordPath := derivedRecordPathForArtifact(t, fileSystem, roots, resolved, artifactPath)
		measured[recordPath] = struct{}{}
	}

	for recordPath, record := range records {
		_, rewritten := measured[recordPath]
		if got, want := record.Owner == derivedOwnerSanctioned, rewritten; got != want {
			t.Errorf(
				"ownership record %q owner = %q, measured sanctioned rewrite = %t",
				recordPath,
				record.Owner,
				rewritten,
			)
		}
	}

	secondOutput, err := runDeclaredRegenerationStepOutput(
		t.Context(), repository, cacheRoot, "make baseline-digests",
	)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Contains(secondOutput, []byte(`"changed":false`)) {
		t.Fatalf("second sanctioned run output = %q, want changed:false", secondOutput)
	}
	second := snapshotDerivedTreeAt(t, baselineRoot, roots)
	if !reflect.DeepEqual(second, after) {
		t.Fatal("second sanctioned run changed the derived tree")
	}
}

func TestDeclaredStepRegenerationAndFrozenBoundaries(t *testing.T) {
	// Sequential: child commands deliberately rewrite one shared fixture.
	repository := newDerivedRegenerationFixture(t)
	baselineRoot := filepath.Join(repository, "internal", "baseline")
	fileSystem := os.DirFS(baselineRoot)
	roots := derivedDigestScanRoots(t)
	records, err := readDerivedOwnershipRecords(fileSystem, roots)
	if err != nil {
		t.Fatal(err)
	}
	resolved, err := validateDerivedOwnership(fileSystem, roots)
	if err != nil {
		t.Fatal(err)
	}
	artifactsByRecord := derivedArtifactsByRecord(t, fileSystem, roots, resolved)
	clean := snapshotDerivedTreeAt(t, baselineRoot, roots)
	cacheRoot := filepath.Join(repository, ".gocache")

	sanctioned := declaredSanctionedProbes(t, records)
	frozen := declaredFrozenProbes(t, records)

	recordPaths := make([]string, 0, len(records))
	for recordPath := range records {
		recordPaths = append(recordPaths, recordPath)
	}
	sort.Strings(recordPaths)
	var dedicatedRecordPath string
	var dedicatedCommand string
	for _, recordPath := range recordPaths {
		record := records[recordPath]
		if record.Owner != derivedOwnerDedicated {
			continue
		}
		if dedicatedRecordPath == "" {
			dedicatedRecordPath = recordPath
			dedicatedCommand = record.Command
		}
		artifacts := artifactsByRecord[recordPath]
		if len(artifacts) == 0 {
			t.Fatalf("dedicated ownership record %q governs no artifacts", recordPath)
		}
		t.Run("dedicated/"+strings.ReplaceAll(recordPath, "/", "_"), func(t *testing.T) {
			rewrite := probesForPaths(artifacts, "dedicated")
			err := exerciseDeclaredRegenerationStep(
				t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
				record.Command, rewrite, frozen,
			)
			if err != nil {
				t.Fatal(err)
			}
			assertDerivedFixtureRestored(t, baselineRoot, roots, clean)
		})
	}
	if dedicatedRecordPath == "" {
		const planCommand = "go test ./internal/baseline -count=1 -run TestBaselinePlanCharacterization -update-baseline-plan-characterization"
		dedicatedRecordPath = "testdata/plan-characterization/_ownership.yml"
		dedicatedCommand = planCommand
		artifacts := artifactsByRecord[dedicatedRecordPath]
		if len(artifacts) == 0 {
			t.Fatalf("synthetic dedicated ownership record %q governs no artifacts", dedicatedRecordPath)
		}
		t.Run("dedicated/synthetic_plan_characterization", func(t *testing.T) {
			writeDedicatedCommandFixture(t, baselineRoot, dedicatedRecordPath, dedicatedCommand)
			err := exerciseDeclaredRegenerationStep(
				t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
				dedicatedCommand, probesForPaths(artifacts, "dedicated"), frozen,
			)
			if err != nil {
				t.Fatal(err)
			}
			assertDerivedFixtureRestored(t, baselineRoot, roots, clean)
		})
	}

	negativeCases := []struct {
		name      string
		command   string
		wantError string
	}{
		{
			name:      "command does not exist",
			command:   "roundfix-declared-step-command-does-not-exist",
			wantError: "run declared command",
		},
		{
			name:      "declared flag is wrong",
			command:   dedicatedCommand + " -roundfix-deliberately-wrong-flag",
			wantError: "run declared command",
		},
		{
			name:      "command leaves artifacts unchanged",
			command:   "go version",
			wantError: "unchanged after deliberate perturbation",
		},
	}
	for _, test := range negativeCases {
		t.Run("failure/"+test.name, func(t *testing.T) {
			writeDedicatedCommandFixture(t, baselineRoot, dedicatedRecordPath, test.command)
			record, err := readDerivedOwnershipRecord(fileSystem, dedicatedRecordPath)
			if err != nil {
				t.Fatal(err)
			}
			err = exerciseDeclaredRegenerationStep(
				t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
				record.Command,
				probesForPaths(artifactsByRecord[dedicatedRecordPath], "dedicated"),
				nil,
			)
			if err == nil || !strings.Contains(err.Error(), test.wantError) {
				t.Fatalf("declared-step error = %v, want %q", err, test.wantError)
			}
			assertDerivedFixtureRestored(t, baselineRoot, roots, clean)
		})
	}

	t.Run("sanctioned command rewrites sanctioned and preserves frozen", func(t *testing.T) {
		err := exerciseDeclaredRegenerationStep(
			t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
			"make baseline-digests", sanctioned, frozen,
		)
		if err != nil {
			t.Fatal(err)
		}
		assertDerivedFixtureRestored(t, baselineRoot, roots, clean)
	})

	t.Run("frozen declaration rejects rewritten directory", func(t *testing.T) {
		const (
			recordPath   = "testdata/catalog.diagnostics.golden.json_ownership.yml"
			artifactPath = "testdata/catalog.diagnostics.golden.json"
		)
		content := []byte("owner: frozen\nreason: deliberately frozen rewrite fixture\n")
		if err := os.WriteFile(
			filepath.Join(baselineRoot, filepath.FromSlash(recordPath)),
			content,
			0o644,
		); err != nil {
			t.Fatalf("write frozen ownership fixture %q: %v", recordPath, err)
		}
		record, err := readDerivedOwnershipRecord(fileSystem, recordPath)
		if err != nil {
			t.Fatal(err)
		}
		err = exerciseDeclaredRegenerationStep(
			t.Context(), repository, baselineRoot, cacheRoot, roots, clean,
			"make baseline-digests", nil,
			[]derivedArtifactProbe{{path: artifactPath, owner: string(record.Owner)}},
		)
		if err == nil || !strings.Contains(err.Error(), "rewrote frozen artifact") {
			t.Fatalf("frozen rewrite error = %v, want rewritten frozen artifact failure", err)
		}
		assertDerivedFixtureRestored(t, baselineRoot, roots, clean)
	})
}

func derivedDigestScanRoots(t *testing.T) []string {
	t.Helper()

	content, err := os.ReadFile("../../Makefile")
	if err != nil {
		t.Fatalf("read Makefile DERIVED_DIGEST_PATHS: %v", err)
	}
	const assignment = "DERIVED_DIGEST_PATHS :="
	for _, line := range strings.Split(string(content), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, assignment) {
			continue
		}
		fields := strings.Fields(strings.TrimSpace(strings.TrimPrefix(line, assignment)))
		if len(fields) == 0 {
			t.Fatal("Makefile DERIVED_DIGEST_PATHS is empty")
		}
		roots := make([]string, 0, len(fields))
		for _, field := range fields {
			const packagePrefix = "internal/baseline/"
			if !strings.HasPrefix(field, packagePrefix) {
				t.Fatalf("derived scan path %q is outside internal/baseline", field)
			}
			roots = append(roots, strings.TrimPrefix(field, packagePrefix))
		}
		return roots
	}
	t.Fatal("Makefile has no DERIVED_DIGEST_PATHS assignment")
	return nil
}

type derivedArtifactSnapshot struct {
	content []byte
	mode    fs.FileMode
}

type derivedArtifactProbe struct {
	path    string
	owner   string
	perturb func([]byte) ([]byte, error)
}

func snapshotDerivedTree(t *testing.T, roots []string) map[string]derivedArtifactSnapshot {
	t.Helper()
	return snapshotDerivedTreeAt(t, ".", roots)
}

func snapshotDerivedTreeAt(
	t *testing.T,
	baselineRoot string,
	roots []string,
) map[string]derivedArtifactSnapshot {
	t.Helper()

	snapshot, err := readDerivedTreeSnapshot(baselineRoot, roots)
	if err != nil {
		t.Fatal(err)
	}
	return snapshot
}

func readDerivedTreeSnapshot(
	baselineRoot string,
	roots []string,
) (map[string]derivedArtifactSnapshot, error) {
	snapshot := make(map[string]derivedArtifactSnapshot)
	fileSystem := os.DirFS(baselineRoot)
	for _, root := range roots {
		if err := fs.WalkDir(fileSystem, root, func(filePath string, entry fs.DirEntry, walkErr error) error {
			if walkErr != nil {
				return fmt.Errorf("walk derived tree %q: %w", filePath, walkErr)
			}
			if entry.IsDir() {
				return nil
			}
			content, err := fs.ReadFile(fileSystem, filePath)
			if err != nil {
				return fmt.Errorf("read derived artifact %q: %w", filePath, err)
			}
			info, err := entry.Info()
			if err != nil {
				return fmt.Errorf("stat derived artifact %q: %w", filePath, err)
			}
			snapshot[path.Clean(filePath)] = derivedArtifactSnapshot{
				content: append([]byte(nil), content...),
				mode:    info.Mode().Perm(),
			}
			return nil
		}); err != nil {
			return nil, fmt.Errorf("snapshot derived tree %q: %w", root, err)
		}
	}
	return snapshot, nil
}

func newDerivedRegenerationFixture(t *testing.T) string {
	t.Helper()

	sourceRoot := filepath.Clean(filepath.Join("..", ".."))
	fixtureRoot := t.TempDir()
	for _, directory := range []string{".agents", "internal", "skills"} {
		if err := os.CopyFS(
			filepath.Join(fixtureRoot, directory),
			os.DirFS(filepath.Join(sourceRoot, directory)),
		); err != nil {
			t.Fatalf("copy regeneration fixture directory %s: %v", directory, err)
		}
	}
	for _, fileName := range []string{"Makefile", "go.mod", "go.sum", "skills-lock.json"} {
		sourcePath := filepath.Join(sourceRoot, fileName)
		content, err := os.ReadFile(sourcePath)
		if err != nil {
			t.Fatalf("read regeneration fixture file %s: %v", fileName, err)
		}
		info, err := os.Stat(sourcePath)
		if err != nil {
			t.Fatalf("stat regeneration fixture file %s: %v", fileName, err)
		}
		if err := os.WriteFile(filepath.Join(fixtureRoot, fileName), content, info.Mode().Perm()); err != nil {
			t.Fatalf("copy regeneration fixture file %s: %v", fileName, err)
		}
	}
	return fixtureRoot
}

func derivedArtifactsByRecord(
	t *testing.T,
	fileSystem fs.FS,
	roots []string,
	resolved map[string]derivedOwnershipRecord,
) map[string][]string {
	t.Helper()

	artifacts := make(map[string][]string)
	for artifactPath := range resolved {
		info, err := fs.Stat(fileSystem, artifactPath)
		if err != nil {
			t.Fatalf("stat resolved derived path %q: %v", artifactPath, err)
		}
		if !info.Mode().IsRegular() {
			continue
		}
		var recordPaths []string
		for _, root := range roots {
			if !pathWithinDerivedScanRoot(artifactPath, root) {
				continue
			}
			recordPaths, err = resolveDerivedOwnershipRecordPaths(
				fileSystem, root, artifactPath, false,
			)
			if err != nil {
				t.Fatalf("resolve ownership for %q: %v", artifactPath, err)
			}
			break
		}
		if len(recordPaths) != 1 {
			t.Fatalf("resolved artifact %q has ownership records %v", artifactPath, recordPaths)
		}
		artifacts[recordPaths[0]] = append(artifacts[recordPaths[0]], artifactPath)
	}
	for recordPath := range artifacts {
		sort.Strings(artifacts[recordPath])
	}
	return artifacts
}

func derivedRecordPathForArtifact(
	t *testing.T,
	fileSystem fs.FS,
	roots []string,
	resolved map[string]derivedOwnershipRecord,
	artifactPath string,
) string {
	t.Helper()

	if _, ok := resolved[artifactPath]; !ok {
		t.Fatalf("changed derived artifact %q has no resolved ownership", artifactPath)
	}
	for _, root := range roots {
		if !pathWithinDerivedScanRoot(artifactPath, root) {
			continue
		}
		recordPaths, err := resolveDerivedOwnershipRecordPaths(
			fileSystem, root, artifactPath, false,
		)
		if err != nil {
			t.Fatalf("resolve ownership for changed artifact %q: %v", artifactPath, err)
		}
		if len(recordPaths) != 1 {
			t.Fatalf("changed artifact %q has ownership records %v", artifactPath, recordPaths)
		}
		return recordPaths[0]
	}
	t.Fatalf("changed derived artifact %q is outside the derived scan", artifactPath)
	return ""
}

