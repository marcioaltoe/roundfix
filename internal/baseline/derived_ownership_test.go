func TestDerivedOwnershipValidatesRecords(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name      string
		record    string
		wantError string
	}{
		{
			name:   "sanctioned with reason",
			record: "owner: sanctioned\nreason: regenerated by the sanctioned command\n",
		},
		{
			name:   "frozen with reason",
			record: "owner: frozen\nreason: intentionally regenerated by nothing\n",
		},
		{
			name: "dedicated with command",
			record: "owner: dedicated\n" +
				"command: go test ./internal/baseline -run TestFixture\n" +
				"reason: uses a dedicated regeneration step\n",
		},
		{
			name:      "unknown owner",
			record:    "owner: inferred\nreason: invalid owner\n",
			wantError: "is not sanctioned, dedicated, or frozen",
		},
		{
			name:      "missing reason",
			record:    "owner: sanctioned\n",
			wantError: "reason is required",
		},
		{
			name:      "dedicated missing command",
			record:    "owner: dedicated\nreason: missing exact invocation\n",
			wantError: "command is required for dedicated ownership",
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()

			fixture := fstest.MapFS{
				"derived/_ownership.yml": &fstest.MapFile{Data: []byte(test.record)},
				"derived/artifact.txt":   &fstest.MapFile{Data: []byte("artifact\n")},
			}
			_, err := validateDerivedOwnership(fixture, []string{"derived"})
			if test.wantError == "" {
				if err != nil {
					t.Fatal(err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), test.wantError) {
				t.Fatalf("validation error = %v, want %q", err, test.wantError)
			}
		})
	}
}

func TestDerivedOwnershipRemediationDiagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name       string
		scanRoot   string
		artifact   string
		recordPath string
		owner      derivedOwnershipOwner
	}{
		{
			name:       "sanctioned setup",
			scanRoot:   "assets/setups",
			artifact:   "assets/setups/go-cli.json",
			recordPath: "assets/setups/_ownership.yml",
			owner:      derivedOwnerSanctioned,
		},
		{
			name:       "sanctioned plan characterization",
			scanRoot:   "testdata",
			artifact:   "testdata/plan-characterization/clean-adoption.golden.json",
			recordPath: "testdata/plan-characterization/_ownership.yml",
			owner:      derivedOwnerSanctioned,
		},
		{
			name:       "sanctioned parity corpus",
			scanRoot:   "testdata",
			artifact:   "testdata/parity-corpus/v1/matrix.json",
			recordPath: "testdata/parity-corpus/_ownership.yml",
			owner:      derivedOwnerSanctioned,
		},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()

			record, err := readDerivedOwnershipRecord(os.DirFS("."), test.recordPath)
			if err != nil {
				t.Fatal(err)
			}
			if record.Owner != test.owner {
				t.Fatalf("ownership record %q owner = %q, want %q", test.recordPath, record.Owner, test.owner)
			}
			got, err := derivedArtifactRemediation(os.DirFS("."), test.scanRoot, test.artifact)
			if err != nil {
				t.Fatal(err)
			}

			switch test.owner {
			case derivedOwnerSanctioned:
				if got != baselineDigestRegenerationHint {
					t.Fatalf("sanctioned remediation = %q, want unchanged %q", got, baselineDigestRegenerationHint)
				}
			case derivedOwnerDedicated:
				if !strings.Contains(got, record.Command) || !strings.Contains(got, test.recordPath) {
					t.Fatalf("dedicated remediation = %q, want command %q and record %q", got, record.Command, test.recordPath)
				}
				if strings.Contains(got, baselineDigestRegenerationHint) {
					t.Fatalf("dedicated remediation = %q, must not suggest sanctioned command", got)
				}
			case derivedOwnerFrozen:
				if !strings.Contains(got, "nothing regenerates this artifact") ||
					!strings.Contains(got, record.Reason) ||
					!strings.Contains(got, test.recordPath) {
					t.Fatalf("frozen remediation = %q, want no regenerator, reason %q, and record %q", got, record.Reason, test.recordPath)
				}
				if strings.Contains(got, baselineDigestRegenerationHint) {
					t.Fatalf("frozen remediation = %q, must not suggest sanctioned command", got)
				}
			}
		})
	}

	t.Run("dedicated fixture", func(t *testing.T) {
		t.Parallel()

		const (
			recordPath = "derived/_ownership.yml"
			command    = "go test ./internal/baseline -run TestFixture -update-fixture"
		)
		fixture := fstest.MapFS{
			recordPath: &fstest.MapFile{Data: []byte(
				"owner: dedicated\ncommand: " + command + "\nreason: fixture\n",
			)},
			"derived/artifact.txt": &fstest.MapFile{Data: []byte("artifact\n")},
		}
		got, err := derivedArtifactRemediation(fixture, "derived", "derived/artifact.txt")
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(got, command) || !strings.Contains(got, recordPath) {
			t.Fatalf("dedicated remediation = %q, want command %q and record %q", got, command, recordPath)
		}
		if strings.Contains(got, baselineDigestRegenerationHint) {
			t.Fatalf("dedicated remediation = %q, must not suggest sanctioned command", got)
		}
	})
}

