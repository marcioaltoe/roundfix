const authoringCommandFixture = `skills:
  authoring:
    claude:
      prd: {model: opus, reasoning_effort: xhigh}
      research: {model: sonnet, tools: [WebSearch]}
`

func TestSkillsInstallAppliesTheAuthoringModelDeclaration(t *testing.T) {
	t.Parallel()
	t.Run("surface_transcript_2", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		// The command must load from the resolved root even from a nested cwd.
		nested := filepath.Join(root, "nested")
		if err := os.Mkdir(nested, 0o755); err != nil {
			t.Fatal(err)
		}
		setCommandWorkDirForTest(t, nested)
		var stdout, stderr bytes.Buffer
		code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
		want := authoringInstallTranscript(t, root)
		if code != 0 || stdout.String() != want || stderr.String() != "" {
			t.Fatalf("exit=%d\nstdout=%s\nstderr=%s\nwant stdout=%s", code, &stdout, &stderr, want)
		}
		assertAuthoringCommandFiles(t, root)
	})
	t.Run("lock_records_the_installed_tree", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		writeAuthoringCommandLock(t, root)
		var stdout, stderr bytes.Buffer
		if code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr); code != 0 || stderr.Len() != 0 {
			t.Fatalf("exit=%d stderr=%s", code, &stderr)
		}
		want := authoringInstallTranscript(t, root) + "Updated skills-lock.json computedHash: roundfix\nUpdated skills-lock.json computedHash: write-prd\n"
		if stdout.String() != want {
			t.Fatalf("stdout=%s want=%s", &stdout, want)
		}
		assertAuthoringCommandLock(t, root)
	})
	t.Run("refuses_a_file_it_did_not_generate", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		path := ".claude/agents/roundfix-prd-author.md"
		writeAuthoringCommandFile(t, root, path, "handwritten\n")
		var stdout, stderr bytes.Buffer
		code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
		want := "roundfix: skills install failed: " + path + " exists and was not generated by Roundfix; move or rename it, then run roundfix skills install --target project again\n"
		if code != 2 || stdout.Len() != 0 || stderr.String() != want {
			t.Fatalf("exit=%d stdout=%s stderr=%s", code, &stdout, &stderr)
		}
		assertNoAuthoringCommandInstall(t, root)
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err != nil || string(got) != "handwritten\n" {
			t.Fatalf("conflict changed: %s %v", got, err)
		}
	})
	t.Run("names_an_uncovered_header", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		writeAuthoringCommandFile(t, root, ".agents/skills/write-tasks/SKILL.md", "---\nname: write-tasks\nmodel: previous\neffort: high\n---\nbody\n")
		var stdout, stderr bytes.Buffer
		code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
		want := "roundfix: notice: .agents/skills/write-tasks/SKILL.md held model or effort lines that no declaration covers; declare skills.authoring.claude.tasks in .roundfixrc.yml to keep them\n"
		if code != 0 || stderr.String() != want || stdout.String() != authoringInstallTranscript(t, root) {
			t.Fatalf("exit=%d stdout=%s stderr=%s", code, &stdout, &stderr)
		}
		assertAuthoringCommandFiles(t, root)
	})
	t.Run("an_invalid_declaration_stops_before_installing", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", "skills: {authoring: {claude: {prd: {reasoning_effort: hihg}}}}\n")
		var stdout, stderr bytes.Buffer
		code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
		want := fmt.Sprintf("roundfix: skills install failed: parse config %q: skills.authoring.claude.prd.reasoning_effort \"hihg\" is not supported for claude; expected low, medium, high, xhigh or max\n", filepath.Join(root, ".roundfixrc.yml"))
		if code != 2 || stdout.Len() != 0 || stderr.String() != want {
			t.Fatalf("exit=%d stdout=%s stderr=%s want=%s", code, &stdout, &stderr, want)
		}
		assertNoAuthoringCommandInstall(t, root)
		if _, err := os.Stat(filepath.Join(root, ".claude")); !os.IsNotExist(err) {
			t.Fatalf(".claude exists: %v", err)
		}
	})
	t.Run("configuration_warnings_reach_stderr", func(t *testing.T) {
		home, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, home, ".roundfix/config.yml", "skills: invalid\n")
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		var stdout, stderr bytes.Buffer
		code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
		if code != 0 || stdout.String() != authoringInstallTranscript(t, root) || stderr.String() != "config: skills in User Config is ignored; set skills in Project Config\n" {
			t.Fatalf("exit=%d stdout=%s stderr=%s", code, &stdout, &stderr)
		}
	})
}

func TestBaselineUpdateAppliesTheAuthoringModelDeclaration(t *testing.T) {
	t.Parallel()
	t.Run("installation_reports_lock_and_removal", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		writeAuthoringCommandLock(t, root)
		var stderr bytes.Buffer
		deps := authoringStageDependencies(t, root, &stderr)
		request := baselineUpdateSkillsRequest{Repository: root}
		result, err := runBaselineUpdateSkillsStageWith(t.Context(), request, deps)
		want := &roundskills.AuthoringInstall{Headers: []string{"write-prd"}, Subagents: []string{".claude/agents/roundfix-prd-author.md", ".claude/agents/roundfix-researcher.md"}}
		if err != nil || result.Status != baselineUpdateSkillsVerified || !reflect.DeepEqual(result.Authoring, want) || stderr.Len() != 0 {
			t.Fatalf("result=%+v authoring=%+v err=%v stderr=%s", result, result.Authoring, err, &stderr)
		}
		assertAuthoringCommandFiles(t, root)
		assertAuthoringCommandLock(t, root)
		report := newBaselineUpdateResult()
		report.Skills = result
		var output bytes.Buffer
		if err := writeBaselineUpdateResult(report, false, &output); err != nil {
			t.Fatal(err)
		}
		anchor := "- installed " + result.Installed[len(result.Installed)-1] + "\nAuthoring models: 1 header(s), 2 generated subagent(s), 0 removed\nSkills lock updated: 2\n"
		if !strings.Contains(output.String(), anchor) {
			t.Fatalf("text=%s", &output)
		}
		output.Reset()
		if err := writeBaselineUpdateResult(report, true, &output); err != nil {
			t.Fatal(err)
		}
		assertAuthoringJSON(t, output.Bytes(), `{"headers":["write-prd"],"subagents":[".claude/agents/roundfix-prd-author.md",".claude/agents/roundfix-researcher.md"]}`)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", "skills: {authoring: {claude: {prd: {model: opus, reasoning_effort: xhigh}}}}\n")
		result, err = runBaselineUpdateSkillsStageWith(t.Context(), request, deps)
		if err != nil || !reflect.DeepEqual(result.Authoring.Removed, []string{".claude/agents/roundfix-researcher.md"}) {
			t.Fatalf("narrowed=%+v err=%v", result.Authoring, err)
		}
		report.Skills = result
		output.Reset()
		if err := writeBaselineUpdateResult(report, false, &output); err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(output.String(), "Authoring models: 1 header(s), 1 generated subagent(s), 1 removed\n") {
			t.Fatalf("text=%s", &output)
		}
		output.Reset()
		if err := writeBaselineUpdateResult(report, true, &output); err != nil {
			t.Fatal(err)
		}
		assertAuthoringJSON(t, output.Bytes(), `{"headers":["write-prd"],"subagents":[".claude/agents/roundfix-prd-author.md"],"removed":[".claude/agents/roundfix-researcher.md"]}`)
	})
	t.Run("uncovered_notice_and_warnings", func(t *testing.T) {
		home, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, home, ".roundfix/config.yml", "skills: invalid\n")
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
		writeAuthoringCommandFile(t, root, ".agents/skills/write-idea/SKILL.md", "---\nmodel: old\neffort: high\n---\n")
		var stderr bytes.Buffer
		result, err := runBaselineUpdateSkillsStageWith(t.Context(), baselineUpdateSkillsRequest{Repository: root}, authoringStageDependencies(t, root, &stderr))
		want := "config: skills in User Config is ignored; set skills in Project Config\nroundfix: notice: .agents/skills/write-idea/SKILL.md held model or effort lines that no declaration covers; declare skills.authoring.claude.idea in .roundfixrc.yml to keep them\n"
		if err != nil || result.Authoring == nil || stderr.String() != want {
			t.Fatalf("result=%+v err=%v stderr=%s", result, err, &stderr)
		}
	})
	for _, failure := range []string{"load", "installation"} {
		t.Run(failure+"_failure", func(t *testing.T) {
			_, root := withCLIWorkspace(t)
			var want string
			if failure == "load" {
				writeAuthoringCommandFile(t, root, ".roundfixrc.yml", "skills: {authoring: {claude: {prd: {reasoning_effort: hihg}}}}\n")
				want = fmt.Sprintf("apply the Authoring Model Declaration: parse config %q: skills.authoring.claude.prd.reasoning_effort \"hihg\" is not supported for claude; expected low, medium, high, xhigh or max", filepath.Join(root, ".roundfixrc.yml"))
			} else {
				writeAuthoringCommandFile(t, root, ".roundfixrc.yml", authoringCommandFixture)
				writeAuthoringCommandFile(t, root, ".claude/agents/roundfix-idea-author.md", "handwritten\n")
				want = "apply the Authoring Model Declaration: .claude/agents/roundfix-idea-author.md exists and was not generated by Roundfix; move or rename it, then run roundfix skills install --target project again"
			}
			var stderr bytes.Buffer
			result, err := runBaselineUpdateSkillsStageWith(t.Context(), baselineUpdateSkillsRequest{Repository: root}, authoringStageDependencies(t, root, &stderr))
			if err == nil || err.Error() != want || result.Status != baselineUpdateSkillsFailed || stderr.Len() != 0 {
				t.Fatalf("result=%+v error=%v want=%s stderr=%s", result, err, want, &stderr)
			}
			assertNoAuthoringCommandInstall(t, root)
		})
	}
	t.Run("no_loader_reads_no_configuration", func(t *testing.T) {
		_, root := withCLIWorkspace(t)
		writeAuthoringCommandFile(t, root, ".roundfixrc.yml", "skills: invalid\n")
		result, err := runBaselineUpdateSkillsStageWith(t.Context(), baselineUpdateSkillsRequest{Repository: root}, ownedLockStageDependencies(root))
		if err != nil || result.Authoring != nil {
			t.Fatalf("result=%+v err=%v", result, err)
		}
	})
}

func TestARepositoryWithoutTheDeclarationPrintsWhatItPrinted(t *testing.T) {
	t.Parallel()
	for _, command := range []string{"skills_check", "doctor", "update_check"} {
		t.Run(command, func(t *testing.T) {
			_, root := withCLIWorkspace(t)
			installAuthoringReportFixture(t)
			if command == "doctor" || command == "update_check" {
				for _, phase := range roundskills.AuthoringPhases() {
					writeAuthoringCommandFile(t, root, "skills/"+phase.Skill+"/SKILL.md", "# Published authoring skill\n")
				}
			}
			var stdout, stderr bytes.Buffer
			switch command {
			case "skills_check":
				assertAuthoringCommand(t, []string{"skills", "check"}, "Roundfix skill check passed: "+strings.Join(roundskills.Names(), ", ")+"\n", "", 0)
			case "doctor":
				configureAuthoringDoctorFixture(t)
				if code := runCLI(t, []string{"doctor"}, &stdout, &stderr); code != 0 || stderr.Len() != 0 || strings.Contains(stdout.String(), "authoring-models:") {
					t.Fatalf("exit=%d stdout=%s stderr=%s", code, &stdout, &stderr)
				}
			case "update_check":
				configureAuthoringUpdateFixture(t)
				for _, format := range []string{"text", "json"} {
					output := runUpdateCheckTest(t, "update", "check", "--format", format)
					if strings.Contains(output, "Authoring models:") || strings.Contains(output, `"authoringModels"`) {
						t.Fatalf("new authoring output without section: %s", output)
					}
				}
			}
			if _, err := os.Stat(filepath.Join(root, ".claude")); !os.IsNotExist(err) {
				t.Fatalf("report created .claude: %v", err)
			}
		})
	}
	for _, command := range []string{"skills_install", "baseline_update"} {
		t.Run(command, func(t *testing.T) {
			for _, configured := range []bool{false, true} {
				t.Run(fmt.Sprint(configured), func(t *testing.T) {
					_, root := withCLIWorkspace(t)
					if configured {
						writeAuthoringCommandFile(t, root, ".roundfixrc.yml", "watch: {max_rounds: 4}\n")
					}
					var stdout, stderr bytes.Buffer
					if command == "skills_install" {
						code := runCLI(t, []string{"skills", "install", "--target", "project"}, &stdout, &stderr)
						files, err := roundskills.Files()
						if err != nil {
							t.Fatal(err)
						}
						want := fmt.Sprintf("Installed Roundfix skill for project: %s (%d file(s))\n", filepath.Join(root, ".agents", "skills"), len(files))
						if code != 0 || stdout.String() != want || stderr.Len() != 0 {
							t.Fatalf("exit=%d stdout=%s stderr=%s want=%s", code, &stdout, &stderr, want)
						}
					} else {
						result, err := runBaselineUpdateSkillsStageWith(t.Context(), baselineUpdateSkillsRequest{Repository: root}, authoringStageDependencies(t, root, &stderr))
						if err != nil || result.Authoring != nil || stderr.Len() != 0 {
							t.Fatalf("result=%+v err=%v stderr=%s", result, err, &stderr)
						}
						report := newBaselineUpdateResult()
						report.Skills = result
						for _, jsonOutput := range []bool{false, true} {
							stdout.Reset()
							if err := writeBaselineUpdateResult(report, jsonOutput, &stdout); err != nil {
								t.Fatal(err)
							}
							if strings.Contains(stdout.String(), "Authoring models:") || strings.Contains(stdout.String(), `"authoring"`) {
								t.Fatalf("report=%s", &stdout)
							}
						}
					}
					files, err := roundskills.Files()
					if err != nil {
						t.Fatal(err)
					}
					for _, file := range files {
						got, err := os.ReadFile(filepath.Join(root, ".agents", "skills", filepath.FromSlash(file.Path)))
						if err != nil || !bytes.Equal(got, file.Data) {
							t.Fatalf("%s differs: %v", file.Path, err)
						}
					}
					if _, err := os.Stat(filepath.Join(root, ".claude")); !os.IsNotExist(err) {
						t.Fatalf(".claude exists: %v", err)
					}
				})
			}
		})
	}
}

func authoringStageDependencies(t *testing.T, root string, stderr *bytes.Buffer) baselineUpdateSkillsDependencies {
	t.Helper()
	deps := ownedLockStageDependencies(root)
	deps.stderr = stderr
	deps.loadAuthoring = baselineAuthoringLoader(commandEnvironmentForTest(t), stderr)
	return deps
}

func writeAuthoringCommandFile(t *testing.T, root, path, content string) {
	t.Helper()
	dest := filepath.Join(root, filepath.FromSlash(path))
	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(dest, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func writeAuthoringCommandLock(t *testing.T, root string) {
	t.Helper()
	stale := strings.Repeat("0", 64)
	writeAuthoringCommandFile(t, root, "skills-lock.json", `{"version":1,"skills":{"roundfix":{"computedHash":"`+stale+`"},"write-prd":{"computedHash":"`+stale+`"}}}`+"\n")
}

func authoringInstallTranscript(t *testing.T, root string) string {
	t.Helper()
	files, err := roundskills.Files()
	if err != nil {
		t.Fatal(err)
	}
	return fmt.Sprintf("Installed Roundfix skill for project: %s (%d file(s))\n", filepath.Join(root, ".agents", "skills"), len(files)) +
		"Applied declared header: write-prd (model opus, effort xhigh)\n" +
		"Generated subagent: .claude/agents/roundfix-prd-author.md\n" +
		"Generated subagent: .claude/agents/roundfix-researcher.md\n"
}

func assertNoAuthoringCommandInstall(t *testing.T, root string) {
	t.Helper()
	if _, err := os.Stat(filepath.Join(root, ".agents")); !os.IsNotExist(err) {
		t.Fatalf("skills installed before refusal: %v", err)
	}
}

func assertAuthoringCommandFiles(t *testing.T, root string) {
	t.Helper()
	files, err := roundskills.Files()
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		want := file.Data
		if file.Path == "write-prd/SKILL.md" {
			want, err = roundskills.ApplyDeclaredHeader(want, roundskills.AuthoringEntry{Model: "opus", Effort: "xhigh"})
			if err != nil {
				t.Fatal(err)
			}
		}
		got, err := os.ReadFile(filepath.Join(root, ".agents", "skills", filepath.FromSlash(file.Path)))
		if err != nil || !bytes.Equal(got, want) {
			t.Fatalf("installed %s differs: %v", file.Path, err)
		}
	}
	for key, entry := range map[string]roundskills.AuthoringEntry{"prd": {Model: "opus", Effort: "xhigh"}, "research": {Model: "sonnet", Tools: []string{"WebSearch"}}} {
		path, want, err := roundskills.GeneratedSubagent("claude", key, entry)
		if err != nil {
			t.Fatal(err)
		}
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err != nil || !bytes.Equal(got, want) {
			t.Fatalf("generated %s differs: %v", path, err)
		}
	}
}

func assertAuthoringCommandLock(t *testing.T, root string) {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, "skills-lock.json"))
	if err != nil {
		t.Fatal(err)
	}
	var lock struct {
		Skills map[string]struct {
			Hash string `json:"computedHash"`
		} `json:"skills"`
	}
	if err := json.Unmarshal(data, &lock); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"roundfix", "write-prd"} {
		hash, err := roundskills.SkillFolderHash(t.Context(), filepath.Join(root, ".agents", "skills", name))
		if err != nil {
			t.Fatal(err)
		}
		if lock.Skills[name].Hash != hash {
			t.Fatalf("%s lock hash=%s installed=%s", name, lock.Skills[name].Hash, hash)
		}
	}
	shippedRoot := t.TempDir()
	if _, err := roundskills.Install(t.Context(), roundskills.InstallRequest{ProjectDir: shippedRoot}); err != nil {
		t.Fatal(err)
	}
	shippedHash, err := roundskills.SkillFolderHash(t.Context(), filepath.Join(shippedRoot, ".agents", "skills", "write-prd"))
	if err != nil {
		t.Fatal(err)
	}
	if lock.Skills["write-prd"].Hash == shippedHash {
		t.Fatal("lock recorded shipped hash without declared header")
	}
}

func assertAuthoringJSON(t *testing.T, payload []byte, want string) {
	t.Helper()
	var report struct {
		Skills struct {
			Authoring json.RawMessage `json:"authoring"`
		} `json:"skills"`
	}
	if err := json.Unmarshal(payload, &report); err != nil {
		t.Fatal(err)
	}
	if string(report.Skills.Authoring) != want {
		t.Fatalf("authoring=%s want=%s", report.Skills.Authoring, want)
	}
}
